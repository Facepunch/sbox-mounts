		float bestDot = 0;
		for ( int i = first; i < Directions.Length; i++ )
		{
			float dot = Vector3.Dot( direction, Directions[i] );
			if ( dot > 0.98f ) return (byte)(i + 1);
			if ( dot <= bestDot ) continue;
			bestDot = dot;
			best = i;
		}
		return (byte)(best + 1);
	}

